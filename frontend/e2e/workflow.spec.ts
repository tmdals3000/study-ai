import { expect, test } from "@playwright/test";
import path from "node:path";
test("PDF → summary → mindmap → quiz → edit card → review → tutor", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "읽은 것을, 내 지식으로." })).toBeVisible();
  await page.getByLabel("PDF 업로드").setInputFiles(path.resolve("e2e/lecture.pdf"));
  await page.getByRole("link", { name: "학습 열기 →" }).last().click();
  await expect(page.getByText("Water freezes at zero degrees Celsius. The Earth orbits the Sun.")).toBeVisible();
  await page.getByRole("button", { name: "요약", exact: true }).click();
  await page.getByRole("button", { name: "생성하기", exact: true }).click();
  await expect(page.getByRole("heading", { name: "핵심 개념", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "마인드맵", exact: true }).click();
  await expect(page.locator("svg.markmap")).toBeVisible();
  await expect(page.locator("svg.markmap foreignObject").first()).toBeVisible();
  await page.getByRole("button", { name: "퀴즈", exact: true }).click();
  await page.getByRole("button", { name: "생성하기", exact: true }).click();
  await expect(page.getByRole("heading", { name: "At what temperature does water freeze?" })).toBeVisible();
  await page.getByRole("radio", { name: "10 C", exact: true }).check();
  await page.getByRole("button", { name: "정답 확인", exact: true }).click();
  await expect(page.getByText("다시 기억해 볼 내용", { exact: true })).toBeVisible();
  await page.getByLabel("오답만 다시 풀기").check();
  await expect(page.getByRole("heading", { name: "At what temperature does water freeze?" })).toBeVisible();
  await page.getByRole("radio", { name: "0 C", exact: true }).check();
  await page.getByRole("button", { name: "정답 확인", exact: true }).click();
  await expect(page.getByText("정답입니다", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "플래시카드", exact: true }).click();
  await page.getByRole("button", { name: "생성하기", exact: true }).click();
  await expect(page.getByRole("heading", { name: "When does water freeze?" })).toBeVisible();
  await page.getByRole("button", { name: "편집", exact: true }).click();
  await page.getByLabel("앞면", { exact: true }).fill("물은 언제 어는가?");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("heading", { name: "물은 언제 어는가?" })).toBeVisible();
  await page.getByRole("link", { name: "복습하기", exact: true }).click();
  await page.getByRole("button", { name: "답 보기", exact: true }).click();
  await expect(page.getByText("At zero degrees Celsius.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "보통", exact: true }).click();
  await expect(page.getByRole("heading", { name: "이번 복습을 마쳤어요." })).toBeVisible();
  await page.getByRole("link", { name: "자료실로 돌아가기", exact: true }).click();
  await page.getByRole("link", { name: "학습 열기 →" }).last().click();
  await page.getByRole("button", { name: "튜터", exact: true }).click();
  await page.getByLabel("튜터에게 질문").fill("When does water freeze?");
  await page.getByRole("button", { name: "질문하기", exact: true }).click();
  await expect(page.getByText("Water freezes at zero degrees Celsius. [p.1]", { exact: true })).toBeVisible();
  await page.getByText("출처 확인", { exact: true }).click();
  await page.getByRole("button", { name: "p.1", exact: true }).click();
  await expect(page.getByRole("button", { name: "원문", exact: true })).toHaveAttribute("aria-current", "page");
  await page.getByRole("link", { name: "내 자료실" }).click();
  await page.screenshot({ path: "../.qa/desktop.png", fullPage: true });
  expect(errors).toEqual([]);
});
test("mobile layout and PWA metadata", async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "읽은 것을, 내 지식으로." })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const manifest = await request.get("/manifest.webmanifest");
  expect(manifest.status()).toBe(200);
  expect((await manifest.json()).display).toBe("standalone");
  expect((await request.get("/icon-192.png")).status()).toBe(200);
  await page.getByRole("link", { name: "학습 열기 →" }).last().click();
  await page.getByRole("button", { name: "퀴즈", exact: true }).click();
  await expect(page.getByRole("heading", { name: "At what temperature does water freeze?" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "../.qa/mobile.png", fullPage: true });
});
